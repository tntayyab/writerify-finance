CREATE TABLE IF NOT EXISTS partner_withdrawals (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  withdrawal_date TEXT NOT NULL,             -- 'YYYY-MM-DD'
  month_key TEXT NOT NULL,                   -- 'YYYY-MM'
  partner TEXT NOT NULL,                     -- 'Mustaqeem' / 'Sazzad'
  amount_bdt NUMERIC NOT NULL DEFAULT 0,
  amount NUMERIC NOT NULL DEFAULT 0,         -- USD equivalent
  exchange_rate NUMERIC DEFAULT 0,
  note TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_partner_withdrawals_date ON partner_withdrawals (withdrawal_date DESC);

ALTER TABLE partner_withdrawals ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Public access partner_withdrawals" ON partner_withdrawals;
CREATE POLICY "Public access partner_withdrawals" ON partner_withdrawals FOR ALL USING (true) WITH CHECK (true);

