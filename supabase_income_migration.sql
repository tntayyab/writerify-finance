-- ==============================================================
-- Writerify Finance — Income Entries migration
-- Run once in Supabase → SQL Editor. Safe to re-run.
-- Powers the "Income" section (product / custom income ledger).
-- ==============================================================

CREATE TABLE IF NOT EXISTS income_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  income_date TEXT NOT NULL,                 -- 'YYYY-MM-DD'
  month_key TEXT NOT NULL,                   -- 'YYYY-MM'
  product TEXT NOT NULL DEFAULT 'Writerify', -- Writerify / Pinterify / Themixify / any custom product
  site_id BIGINT REFERENCES sites(id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  description TEXT DEFAULT '',
  amount NUMERIC NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_income_entries_date ON income_entries (income_date DESC);
CREATE INDEX IF NOT EXISTS idx_income_entries_month ON income_entries (month_key);
CREATE INDEX IF NOT EXISTS idx_income_entries_product ON income_entries (product);

ALTER TABLE income_entries ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Public access income_entries" ON income_entries;
CREATE POLICY "Public access income_entries" ON income_entries FOR ALL USING (true) WITH CHECK (true);

-- Make PostgREST pick up the new table immediately
NOTIFY pgrst, 'reload schema';
