  function resolveRange(preset, custom) {
    const now = new Date();
    const y = now.getFullYear();
    const m = now.getMonth();
    const lastDay = (yy, mm) => new Date(yy, mm + 1, 0).getDate();
    switch (preset) {
      case 'active': {
        const [ay, am] = state.activeMonth.split('-').map(Number);
        return { from: `${ay}-${pad(am)}-01`, to: `${ay}-${pad(am)}-${pad(lastDay(ay, am - 1))}` };
      }
      case 'today': return { from: todayStr(), to: todayStr() };
      case 'this_month': return { from: `${y}-${pad(m + 1)}-01`, to: `${y}-${pad(m + 1)}-${pad(lastDay(y, m))}` };
      case 'last_month': {
        const d = new Date(y, m - 1, 1);
        return { from: `${d.getFullYear()}-${pad(d.getMonth() + 1)}-01`, to: `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(lastDay(d.getFullYear(), d.getMonth()))}` };
      }
      case 'last_30': return { from: fmtDate(new Date(y, m, now.getDate() - 29)), to: todayStr() };
      case 'this_year': return { from: `${y}-01-01`, to: `${y}-12-31` };
      case 'last_year': return { from: `${y - 1}-01-01`, to: `${y - 1}-12-31` };
      case 'custom': return { from: custom.from || null, to: custom.to || null };
      default: return { from: null, to: null }; // lifetime
    }
  }

  function createPeriod(root, { presets, defaultPreset, storageKey, onChange }) {
    let preset = defaultPreset;
    const custom = { from: '', to: '' };
    try {
      const saved = storageKey && localStorage.getItem(storageKey);
      if (saved && presets.includes(saved)) preset = saved;
    } catch (_) { /* ignore */ }

    const label = (p) => (p === 'active' ? formatMonthLabel(state.activeMonth) : PRESET_LABELS[p]);

    root.innerHTML = `<div class="chips"></div>
      <div class="custom-range hidden"><span>FROM</span><input type="date" class="input" data-k="from"><span>TO</span><input type="date" class="input" data-k="to"></div>`;
    const chipsEl = root.querySelector('.chips');
    const customEl = root.querySelector('.custom-range');

    function drawChips() {
      chipsEl.innerHTML = presets.map((p) => `<button type="button" class="chip ${p === preset ? 'active' : ''}" data-p="${p}">${p === 'custom' ? ic('calendar', 'xs') : ''}${esc(label(p))}</button>`).join('');
      customEl.classList.toggle('hidden', preset !== 'custom');
    }

    chipsEl.addEventListener('click', (e) => {
      const b = e.target.closest('.chip');
      if (!b) return;
      preset = b.dataset.p;
      try { if (storageKey) localStorage.setItem(storageKey, preset); } catch (_) { /* ignore */ }
      drawChips();
      onChange();
    });
    customEl.addEventListener('change', (e) => {
      const k = e.target.dataset.k;
      if (!k) return;
      custom[k] = e.target.value;
      onChange();
    });

    drawChips();

    return {
      range: () => resolveRange(preset, custom),
      preset: () => preset,
      refreshLabels: drawChips,
      describe() {
        const r = resolveRange(preset, custom);
        if (preset === 'lifetime') return 'All time';
        if (!r.from && !r.to) return 'Pick a date range';
        const base = preset === 'custom' ? '' : `${label(preset)} · `;
        if (r.from && r.to && r.from === r.to) return base + prettyDate(r.from);
        return `${base}${r.from ? prettyDate(r.from) : '…'} → ${r.to ? prettyDate(r.to) : '…'}`;
      },
      match(dateStr) {
        const r = resolveRange(preset, custom);
        if (!dateStr) return !r.from && !r.to;
        const d = String(dateStr).slice(0, 10);
        return (!r.from || d >= r.from) && (!r.to || d <= r.to);
      }
    };
  }

