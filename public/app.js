  function resolveRange(preset, custom) {
    const now = new Date();
    const y = now.getFullYear();
    const m = now.getMonth();
    const lastDay = (yy, mm) => new Date(yy, mm + 1, 0).getDate();
    switch (preset) {
      case 'month': {
        const [ay, am] = custom.month.split('-').map(Number);
        return { from: `${ay}-${pad(am)}-01`, to: `${ay}-${pad(am)}-${pad(lastDay(ay, am - 1))}` };
      }
      case 'today': return { from: todayStr(), to: todayStr() };
      case 'this_month': return { from: `${y}-${pad(m + 1)}-01`, to: `${y}-${pad(m + 1)}-${pad(lastDay(y, m))}` };
      case 'last_month': {
        const d = new Date(y, m - 1, 1);
        return { from: `${d.getFullYear()}-${pad(d.getMonth() + 1)}-01`, to: `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(lastDay(d.getFullYear(), d.getMonth()))}` };
      }
      case 'last_30': return { from: fmtDate(new Date(y, m, now.getDate() - 29)), to: todayStr() };
      case 'this_year': return { from: `${y}-01-01`, to: `${y}-12-31` };
      case 'last_year': return { from: `${y - 1}-01-01`, to: `${y - 1}-12-31` };
      case 'custom': return { from: custom.from || null, to: custom.to || null };
      default: return { from: null, to: null }; // lifetime
    }
  }

