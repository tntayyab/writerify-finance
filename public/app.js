  function createTable(cfg) {
    const table = cfg.table;
    const thead = table.querySelector('thead');
    const tbody = table.querySelector('tbody');
    const tfoot = document.createElement('tfoot');
    table.appendChild(tfoot);
    let size = 25;
    try {
      const saved = parseInt(localStorage.getItem(`wf_pagesize_${cfg.key}`), 10);
      if (PAGE_SIZES.includes(saved)) size = saved;
    } catch (_) { /* ignore */ }
    const st = { page: 1, size, sort: { ...cfg.defaultSort }, sorted: [] };

    function renderHead() {
      thead.innerHTML = '<tr>' + cfg.columns.map((c) => {
        const on = st.sort.key === c.key;
        const al = c.align === 'right' ? 'right' : c.align === 'center' ? 'center' : '';
        return `<th class="${c.sortable ? 'sortable' : ''} ${on ? 'sorted' : ''} ${al}" data-key="${c.key}" data-dir="${on ? st.sort.dir : ''}" ${c.width ? `style="width:${c.width}"` : ''}>${c.label}${c.sortable ? '<span class="sort"><i class="up"></i><i class="down"></i></span>' : ''}</th>`;
      }).join('') + '</tr>';
    }

    function sortRows(rows) {
      const col = cfg.columns.find((c) => c.key === st.sort.key);
      if (!col || !col.sortValue) return rows;
      const dir = st.sort.dir === 'asc' ? 1 : -1;
      return [...rows].sort((a, b) => {
        const x = col.sortValue(a);
        const y = col.sortValue(b);
        if (x === y) return 0;
        if (typeof x === 'string' || typeof y === 'string') return String(x).localeCompare(String(y), undefined, { numeric: true, sensitivity: 'base' }) * dir;
        return (x - y) * dir;
      });
    }

    function pageList(page, pages) {
      if (pages <= 7) return Array.from({ length: pages }, (_, i) => i + 1);
      const set = new Set([1, 2, pages - 1, pages, page - 1, page, page + 1]);
      const list = [...set].filter((p) => p >= 1 && p <= pages).sort((a, b) => a - b);
      const out = [];
      list.forEach((p, i) => {
        if (i && p - list[i - 1] > 1) out.push('…');
        out.push(p);
      });
      return out;
    }

    function renderPager(total, start, end, pages) {
      const el = cfg.pager;
      const sizeOpts = PAGE_SIZES.map((n) => `<option value="${n}" ${n === st.size ? 'selected' : ''}>${n === 0 ? 'All' : n}</option>`).join('');
      const info = total ? `Showing <b>${start + 1}–${end}</b> of <b>${total.toLocaleString()}</b>` : 'No results';
      let pagesHtml = '';
      if (pages > 1) {
        pagesHtml = `<button class="pg nav-pg" data-page="prev" ${st.page <= 1 ? 'disabled' : ''}>${ic('chev-left', 'xs')}Prev</button>` +
          pageList(st.page, pages).map((p) => (p === '…' ? '<span class="pg dots">…</span>' : `<button class="pg ${p === st.page ? 'active' : ''}" data-page="${p}">${p}</button>`)).join('') +
          `<button class="pg nav-pg" data-page="next" ${st.page >= pages ? 'disabled' : ''}>Next${ic('chev-right', 'xs')}</button>`;
      }
      el.innerHTML = `<div class="pager-left"><span>${info}</span><label>Rows per page<select class="select select-sm" data-size>${sizeOpts}</select></label></div><div class="pager-pages">${pagesHtml}</div>`;
    }

    function render() {
      const all = cfg.getRows();
      const rows = sortRows(all);
      st.sorted = rows;
      const total = rows.length;
      const perPage = st.size === 0 ? Math.max(total, 1) : st.size;
      const pages = Math.max(1, Math.ceil(total / perPage));
      st.page = Math.min(Math.max(1, st.page), pages);
      const start = (st.page - 1) * perPage;
      const end = Math.min(start + perPage, total);
      renderHead();
      tbody.innerHTML = total
        ? rows.slice(start, end).map((r, i) => cfg.row(r, start + i)).join('')
        : `<tr><td colspan="${cfg.columns.length}">${cfg.empty()}</td></tr>`;
      renderFoot();
      renderPager(total, start, end, pages);
      if (cfg.onRender) cfg.onRender(rows);
    }

    function renderFoot() {
      tfoot.innerHTML = cfg.foot && st.sorted.length ? cfg.foot(st.sorted) : '';
    }

    thead.addEventListener('click', (e) => {
      const th = e.target.closest('th.sortable');
      if (!th) return;
      const key = th.dataset.key;
      const col = cfg.columns.find((c) => c.key === key);
      if (st.sort.key === key) st.sort.dir = st.sort.dir === 'asc' ? 'desc' : 'asc';
      else st.sort = { key, dir: col.firstDir || 'asc' };
      st.page = 1;
      render();
    });

    cfg.pager.addEventListener('click', (e) => {
      const b = e.target.closest('[data-page]');
      if (!b || b.disabled) return;
      const v = b.dataset.page;
      st.page = v === 'prev' ? st.page - 1 : v === 'next' ? st.page + 1 : parseInt(v, 10);
      render();
      table.closest('.card').scrollIntoView({ behavior: 'smooth', block: 'start' });
    });
    cfg.pager.addEventListener('change', (e) => {
      if (!e.target.matches('[data-size]')) return;
      st.size = parseInt(e.target.value, 10);
      st.page = 1;
      try { localStorage.setItem(`wf_pagesize_${cfg.key}`, String(st.size)); } catch (_) { /* ignore */ }
      render();
    });

    if (cfg.onAction) {
      tbody.addEventListener('click', (e) => {
        const b = e.target.closest('[data-act]');
        if (b) cfg.onAction(b.dataset.act, b.dataset.id, b);
      });
    }
    if (cfg.onCellChange) {
      tbody.addEventListener('change', (e) => cfg.onCellChange(e.target));
      tbody.addEventListener('keydown', (e) => { if (e.key === 'Enter' && e.target.matches('.cell-input')) e.target.blur(); });
    }

    return {
      render,
      renderFoot,
      resetPage() { st.page = 1; },
      rows: () => st.sorted,
      body: tbody
    };
  }

