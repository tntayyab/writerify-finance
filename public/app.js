  async function apiFetch(endpoint, options = {}) {
    const token = getAuthToken();
    const headers = { 'Content-Type': 'application/json', ...(token ? { Authorization: `Bearer ${token}` } : {}), ...(options.headers || {}) };
    try {
      const res = await fetch(endpoint, { ...options, headers });
      if (res.status === 401) {
        setAuthToken(null);
        clearSnapshot();
        showLoginScreen();
        throw new Error('Session expired. Please sign in again.');
      }
      if (!res.ok) {
        let body = {};
        try { body = await res.json(); } catch (_) { /* non-JSON error */ }
        let msg = body.error || body.message || `HTTP error ${res.status}`;
        if (/23505|unique constraint|sites_site_url_key|Duplicate URL/i.test(msg)) {
          msg = 'This website URL is already in your portfolio (duplicate URL).';
        }
        showToast(msg, 'error');
        return { ...body, success: false, error: msg };
      }
      return await res.json();
    } catch (err) {
      showToast(err.message, 'error');
      return { success: false, error: err.message };
    }
  }

  // Authenticated file download (keeps the token out of the URL)
  async function downloadFile(endpoint, fallbackName) {
    try {
      const res = await fetch(endpoint, { headers: { Authorization: `Bearer ${getAuthToken()}` } });
      if (!res.ok) throw new Error(`Download failed (${res.status})`);
      const cd = res.headers.get('Content-Disposition') || '';
      const m = /filename="?([^";]+)"?/i.exec(cd);
      const blob = await res.blob();
      const a = document.createElement('a');
      a.href = URL.createObjectURL(blob);
      a.download = m ? m[1] : fallbackName;
      document.body.appendChild(a);
      a.click();
      a.remove();
      setTimeout(() => URL.revokeObjectURL(a.href), 4000);
      showToast('Download started');
    } catch (err) {
      showToast(err.message, 'error');
    }
  }

