  function compactBdt(n) {
    const a = Math.abs(n);
    const s = a >= 1e5 ? (a / 1e5).toFixed(1).replace(/\.0$/, '') + 'L' : a >= 1e3 ? (a / 1e3).toFixed(a >= 1e4 ? 0 : 1).replace(/\.0$/, '') + 'k' : String(Math.round(a));
    return (n < 0 ? '-৳' : '৳') + s;
  }

