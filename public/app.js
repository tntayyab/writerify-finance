    $('targetsForm').addEventListener('submit', async (e) => {
      e.preventDefault();
      const res = await apiFetch('/api/targets', { method: 'POST', body: JSON.stringify({ goalSites: parseInt($('inputGoalSites').value, 10), goalMonthlyIncome: parseFloat($('inputGoalIncome').value) }) });
      if (res.success) { showToast('Mission targets updated ✓'); await loadSummary(); }
    });

    // Open modals
    const openSite = () => openSiteModal(null);
    $('openAddSiteModalBtn').addEventListener('click', openSite);
    $('topbarAddSiteBtn').addEventListener('click', openSite);
    $('openAddIncomeModalBtn').addEventListener('click', () => openIncomeModal(null));
    $('topAddIncomeBtn').addEventListener('click', () => openIncomeModal(null));
    $('openAddCostModalBtn').addEventListener('click', () => openCostModal(null));
    $('topAddCostBtn').addEventListener('click', () => openCostModal(null));
    $('openRestoreBtn').addEventListener('click', () => openModal('restoreModal'));

