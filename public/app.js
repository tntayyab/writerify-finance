  // Running balance of each partner, month by month
  function renderEqLines(el, months) {
    if (!months.length) { el.innerHTML = ''; return; }
    const series = EQ_PARTNERS.map((p) => {
      const pts = months.map((_, i) => eqTotals(months.slice(0, i + 1))['bal' + p.name]);
      return { ...p, pts };
    });
    const W = 760, H = 260, L = 52, R = 84, T = 14, B = 28;
    const ih = H - T - B;
    const iw = W - L - R;
    const vals = series.flatMap((s) => s.pts);
    const hi = Math.max(1000, ...vals);
    const lo = Math.min(0, ...vals);
    const step = niceStep(hi - lo);
    const yMax = Math.ceil(hi / step) * step;
    const yMin = Math.floor(lo / step) * step;
    const y = (v) => T + ih - ((v - yMin) / (yMax - yMin)) * ih;
    const x = (i) => L + (months.length > 1 ? (iw * i) / (months.length - 1) : iw / 2);
    let g = '';
    for (let v = yMin; v <= yMax + 0.001; v += step) {
      g += `<line x1="${L}" x2="${L + iw}" y1="${y(v)}" y2="${y(v)}" stroke="var(--line)" ${v ? 'stroke-dasharray="3 5"' : ''}/>`;
      g += `<text x="${L - 8}" y="${y(v) + 4}" text-anchor="end" font-size="10.5" font-weight="600" fill="var(--text-3)">${compactBdt(v)}</text>`;
    }
    const every = months.length > 14 ? 3 : months.length > 8 ? 2 : 1;
    months.forEach((m, i) => {
      if (i % every === 0) g += `<text x="${x(i)}" y="${H - 8}" text-anchor="middle" font-size="11" font-weight="600" fill="var(--text-3)">${monthShort(m.month_key)}</text>`;
    });
    let lines = '';
    const ends = series.map((s) => ({ s, y: y(s.pts[s.pts.length - 1]) })).sort((a, b) => a.y - b.y);
    if (ends.length === 2 && ends[1].y - ends[0].y < 16) ends[1].y = ends[0].y + 16;
    series.forEach((s) => {
      const d = s.pts.map((v, i) => `${i ? 'L' : 'M'}${x(i)},${y(v)}`).join(' ');
      const lastY = y(s.pts[s.pts.length - 1]);
      lines += `<path class="eq-line" pathLength="1" d="${d}" fill="none" stroke="${s.color}" stroke-width="2" stroke-linejoin="round" stroke-linecap="round"/>`;
      lines += `<circle cx="${x(months.length - 1)}" cy="${lastY}" r="4" fill="${s.color}" stroke="var(--surface-solid)" stroke-width="2"/>`;
    });
    ends.forEach(({ s, y: ly }) => { lines += `<text x="${L + iw + 10}" y="${ly + 4}" font-size="11.5" font-weight="700" fill="var(--text)">${s.name}</text>`; });
    const hover = `<line class="eq-cross" x1="0" x2="0" y1="${T}" y2="${T + ih}" stroke="var(--line-strong)" visibility="hidden"/>` +
      series.map((s) => `<circle class="eq-dot" data-k="${s.key}" r="4.5" fill="${s.color}" stroke="var(--surface-solid)" stroke-width="2" visibility="hidden"/>`).join('');
    el.innerHTML = `<svg viewBox="0 0 ${W} ${H}" role="img" aria-label="Running balance of each partner">${g}${lines}${hover}<rect class="eq-hit" x="${L - 10}" y="${T}" width="${iw + 20}" height="${ih}" fill="transparent"/></svg><div class="chart-tip"></div>`;
    const svg = el.querySelector('svg');
    const tip = el.querySelector('.chart-tip');
    const cross = svg.querySelector('.eq-cross');
    const dots = [...svg.querySelectorAll('.eq-dot')];
    svg.addEventListener('mousemove', (e) => {
      const box = svg.getBoundingClientRect();
      const px = ((e.clientX - box.left) / box.width) * W;
      const i = months.length > 1 ? Math.max(0, Math.min(months.length - 1, Math.round(((px - L) / iw) * (months.length - 1)))) : 0;
      cross.setAttribute('x1', x(i)); cross.setAttribute('x2', x(i)); cross.setAttribute('visibility', 'visible');
      dots.forEach((d, n) => { d.setAttribute('cx', x(i)); d.setAttribute('cy', y(series[n].pts[i])); d.setAttribute('visibility', 'visible'); });
      tip.innerHTML = `<b>${esc(formatMonthLabel(months[i].month_key))}</b>` + series.map((s) => `<div><span>${s.name}</span><span>${bdt(Math.round(s.pts[i]))}</span></div>`).join('');
      tip.style.left = `${(Math.min(Math.max(x(i), 90), W - 90) / W) * 100}%`;
      tip.style.top = '34%';
      tip.classList.add('show');
    });
    svg.addEventListener('mouseleave', () => {
      tip.classList.remove('show');
      cross.setAttribute('visibility', 'hidden');
      dots.forEach((d) => d.setAttribute('visibility', 'hidden'));
    });
  }

