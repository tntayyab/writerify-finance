  // Continuous month list, so a month without activity still shows on the axis
  function eqAllMonths() {
    const raw = (state.equity && state.equity.months) || [];
    if (!raw.length) return [];
    const byKey = Object.fromEntries(raw.map((m) => [m.month_key, m]));
    const last = [raw[raw.length - 1].month_key, getCurrentMonthKey()].sort()[1];
    const out = [];
    let [y, m] = raw[0].month_key.split('-').map(Number);
    for (let guard = 0; guard < 240; guard++) {
      const key = `${y}-${pad(m)}`;
      out.push(byKey[key] || { month_key: key, income: 0, company_cost: 0, sazzad_cost: 0, mustaqeem_cost: 0, sazzad_withdrawn: 0, mustaqeem_withdrawn: 0 });
      if (key === last) break;
      m += 1;
      if (m > 12) { m = 1; y += 1; }
    }
    return out;
  }

  function eqTotals(list) {
    const t = list.reduce((a, m) => {
      a.income += m.income; a.company += m.company_cost;
      a.sazzad += m.sazzad_cost; a.mustaqeem += m.mustaqeem_cost;
      a.wSazzad += m.sazzad_withdrawn; a.wMustaqeem += m.mustaqeem_withdrawn;
      return a;
    }, { income: 0, company: 0, sazzad: 0, mustaqeem: 0, wSazzad: 0, wMustaqeem: 0 });
    t.net = t.income - t.company - t.sazzad - t.mustaqeem;
    t.share = t.net / 2;
    t.entMustaqeem = t.share + t.mustaqeem;
    t.entSazzad = t.share + t.sazzad;
    t.balMustaqeem = t.entMustaqeem - t.wMustaqeem;
    t.balSazzad = t.entSazzad - t.wSazzad;
    t.cash = t.income - t.company - t.wSazzad - t.wMustaqeem;
    return t;
  }

