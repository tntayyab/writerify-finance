  function productBreakdown(entries, { includePresets = true } = {}) {
    const map = new Map();
    const touch = (name) => {
      const key = name.toLowerCase();
      if (!map.has(key)) map.set(key, { name, total: 0, count: 0, sites: new Set() });
      return map.get(key);
    };
    if (includePresets) { PRODUCT_PRESETS.forEach(touch); state.products.forEach(touch); }
    entries.forEach((e) => {
      const p = touch(e.product || 'Uncategorized');
      p.total += e.amount;
      p.count += 1;
      if (e.site_id) p.sites.add(String(e.site_id));
    });
    const grand = [...map.values()].reduce((a, p) => a + p.total, 0);
    return [...map.values()]
      .map((p) => ({ ...p, sites: p.sites.size, share: grand ? (p.total / grand) * 100 : 0 }))
      .sort((a, b) => b.total - a.total || a.name.localeCompare(b.name));
  }

