-- 1. Settings Table
CREATE TABLE IF NOT EXISTS settings (
  key TEXT PRIMARY KEY,
  value TEXT NOT NULL
);

-- 2. Sites Table
CREATE TABLE IF NOT EXISTS sites (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_url TEXT UNIQUE NOT NULL,
  site_name TEXT,
  username TEXT DEFAULT '',
  status TEXT DEFAULT 'running', -- 'running', 'penalty', 'deleted', 'sold'
  domain_registrar TEXT DEFAULT '',
  hosting_provider TEXT DEFAULT '',
  domain_expiry TEXT DEFAULT '',
  amazon_account TEXT DEFAULT '',
  amazon_tracking_id TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. Monthly Site Metrics Table
CREATE TABLE IF NOT EXISTS monthly_site_metrics (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  site_id BIGINT NOT NULL REFERENCES sites(id) ON DELETE CASCADE,
  month_key TEXT NOT NULL, -- e.g. '2026-10'
  articles_count INTEGER DEFAULT 0,
  cost NUMERIC DEFAULT 0.0,
  ads_income NUMERIC DEFAULT 0.0,
  amazon_income NUMERIC DEFAULT 0.0,
  other_income NUMERIC DEFAULT 0.0,
  notes TEXT DEFAULT '',
  updated_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(site_id, month_key)
);

-- 4. Expenses Ledger Table
CREATE TABLE IF NOT EXISTS expenses_ledger (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  expense_date TEXT NOT NULL,
  month_key TEXT NOT NULL,
  site_id BIGINT REFERENCES sites(id) ON DELETE SET NULL,
  category TEXT NOT NULL,
  title TEXT NOT NULL,
  amount NUMERIC NOT NULL,
  receipt_url TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW()
);

-- Enable Row Level Security (RLS) & Allow Full Access for App
ALTER TABLE settings ENABLE ROW LEVEL SECURITY;
ALTER TABLE sites ENABLE ROW LEVEL SECURITY;
ALTER TABLE monthly_site_metrics ENABLE ROW LEVEL SECURITY;
ALTER TABLE expenses_ledger ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public access settings" ON settings;
CREATE POLICY "Public access settings" ON settings FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access sites" ON sites;
CREATE POLICY "Public access sites" ON sites FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access monthly_site_metrics" ON monthly_site_metrics;
CREATE POLICY "Public access monthly_site_metrics" ON monthly_site_metrics FOR ALL USING (true) WITH CHECK (true);

DROP POLICY IF EXISTS "Public access expenses_ledger" ON expenses_ledger;
CREATE POLICY "Public access expenses_ledger" ON expenses_ledger FOR ALL USING (true) WITH CHECK (true);

-- Writerify Finance — Income Entries migration
-- Run once in Supabase → SQL Editor. Safe to re-run.
-- Powers the "Income" section (product / custom income ledger).

CREATE TABLE IF NOT EXISTS income_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  income_date TEXT NOT NULL,                 -- 'YYYY-MM-DD'
  month_key TEXT NOT NULL,                   -- 'YYYY-MM'
  product TEXT NOT NULL DEFAULT 'Writerify', -- Writerify / Pinterify / Themixify / any custom product
  site_id BIGINT REFERENCES sites(id) ON DELETE SET NULL,
  title TEXT NOT NULL,
  description TEXT DEFAULT '',
  amount NUMERIC NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_income_entries_date ON income_entries (income_date DESC);
CREATE INDEX IF NOT EXISTS idx_income_entries_month ON income_entries (month_key);
CREATE INDEX IF NOT EXISTS idx_income_entries_product ON income_entries (product);

ALTER TABLE income_entries ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Public access income_entries" ON income_entries;
CREATE POLICY "Public access income_entries" ON income_entries FOR ALL USING (true) WITH CHECK (true);

